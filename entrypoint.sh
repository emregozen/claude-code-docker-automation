#!/bin/bash
set -e

echo "🚀 Claude Code GitHub Automation"
echo "================================"

# Validate required environment variables
if [ -z "$ANTHROPIC_API_KEY" ]; then
    echo "❌ Error: ANTHROPIC_API_KEY environment variable is required"
    exit 1
fi

if [ -z "$GITHUB_TOKEN" ]; then
    echo "❌ Error: GITHUB_TOKEN environment variable is required"
    exit 1
fi

if [ -z "$GITHUB_REPO" ]; then
    echo "❌ Error: GITHUB_REPO environment variable is required (format: owner/repo)"
    exit 1
fi

# Configure git
echo "🔐 Configuring git..."
git config --global user.email "${GIT_EMAIL:-claude-bot@example.com}"
git config --global user.name "${GIT_NAME:-Claude Bot}"
echo "✅ Git configured"

# Authenticate GitHub CLI
echo "🔐 Authenticating with GitHub..."
echo "$GITHUB_TOKEN" | gh auth login --with-token 2>&1 || true
echo "✅ GitHub authentication completed"

# Determine prompt source
if [ -n "$PROMPT" ]; then
    CLAUDE_PROMPT="$PROMPT"
elif [ -n "$PROMPT_FILE" ] && [ -f "$PROMPT_FILE" ]; then
    CLAUDE_PROMPT=$(cat "$PROMPT_FILE")
elif [ -n "$1" ]; then
    CLAUDE_PROMPT="$1"
else
    echo "❌ Error: No prompt provided"
    exit 1
fi

echo ""
echo "📋 Configuration:"
echo "   Repository: $GITHUB_REPO"
echo "   Source Branch: ${SOURCE_BRANCH:-main}"
echo "   Prompt: $CLAUDE_PROMPT"
echo ""

# Clone the repository
echo "📦 Cloning repository..."
CLONE_DIR="/workspace/repo"
rm -rf "$CLONE_DIR"

git clone "https://${GITHUB_TOKEN}@github.com/${GITHUB_REPO}.git" "$CLONE_DIR" 2>&1
cd "$CLONE_DIR"
echo "✅ Repository cloned"
echo "📁 Working directory: $(pwd)"

# Checkout source branch
SOURCE_BRANCH="${SOURCE_BRANCH:-main}"
echo "🌿 Checking out branch: $SOURCE_BRANCH"
git fetch origin "$SOURCE_BRANCH" 2>&1
git checkout "$SOURCE_BRANCH" 2>&1
git pull origin "$SOURCE_BRANCH" 2>&1
echo "✅ Branch checked out"

# Create a new branch for changes
TIMESTAMP=$(date +%s)
BRANCH_NAME="${BRANCH_NAME:-claude-changes-${TIMESTAMP}}"
echo "🌱 Creating new branch: $BRANCH_NAME"
git checkout -b "$BRANCH_NAME" 2>&1
echo "✅ New branch created"

# Show initial state
echo ""
echo "📂 Files before Claude Code:"
ls -la

# Run Claude Code in headless mode
echo ""
echo "🤖 Running Claude Code..."
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "Prompt: $CLAUDE_PROMPT"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

claude -p "$CLAUDE_PROMPT" \
    --dangerously-skip-permissions \
    --output-format json \
    --allowedTools "Bash,Read,Write,Edit" \
    2>&1 | tee /tmp/claude-output.json

echo ""
echo "✅ Claude Code execution completed"

# Show files after Claude Code ran
echo ""
echo "📂 Files after Claude Code:"
ls -la

# Show git status
echo ""
echo "📊 Git status:"
git status

# Check for ANY changes (tracked, untracked, modified)
echo ""
echo "🔍 Checking for changes..."

# Add all files (including untracked)
git add -A

# Check if there are changes to commit
if git diff --cached --quiet; then
    echo ""
    echo "ℹ️  No changes detected"
    echo "   Claude Code may not have made any modifications"
    echo "   or changes were not saved to disk"
    
    # Show what Claude said in its output
    echo ""
    echo "📄 Claude Code output:"
    if [ -f /tmp/claude-output.json ]; then
        cat /tmp/claude-output.json | jq -r '.result' 2>/dev/null || cat /tmp/claude-output.json
    fi
else
    echo ""
    echo "📝 Changes detected! Committing..."
    
    # Show what changed
    echo ""
    echo "📋 Changed files:"
    git status --short
    
    echo ""
    echo "📄 Detailed changes:"
    git diff --cached --stat
    
    # Commit changes
    COMMIT_MESSAGE="${COMMIT_MESSAGE:-🤖 Claude Code: $CLAUDE_PROMPT}"
    git commit -m "$COMMIT_MESSAGE"
    echo "✅ Changes committed"
    
    # Push to remote
    echo ""
    echo "⬆️  Pushing branch to GitHub..."
    git push -u origin "$BRANCH_NAME" 2>&1
    echo "✅ Branch pushed"
    
    # Create pull request
    echo ""
    echo "🔀 Creating pull request..."
    
    PR_TITLE="${PR_TITLE:-🤖 Claude Code: Automated changes}"
    PR_BODY="${PR_BODY:-## 🤖 Automated Changes by Claude Code

This PR contains automated changes made by Claude Code.

### 📋 Task Prompt
\`\`\`
$CLAUDE_PROMPT
\`\`\`

### 📊 Details
- **Source Branch:** $SOURCE_BRANCH
- **New Branch:** $BRANCH_NAME
- **Timestamp:** $(date -u +"%Y-%m-%d %H:%M:%S UTC")
- **Repository:** $GITHUB_REPO

### 📝 Summary of Changes
$(git diff --cached --stat origin/$SOURCE_BRANCH 2>/dev/null || echo "See commit history for details")

---
*Generated by Claude Code Automation*}"
    
    BASE_BRANCH="${BASE_BRANCH:-${SOURCE_BRANCH}}"
    
    # Create PR and capture output
    echo "Creating PR from $BRANCH_NAME to $BASE_BRANCH..."
    PR_OUTPUT=$(gh pr create \
        --repo "$GITHUB_REPO" \
        --title "$PR_TITLE" \
        --body "$PR_BODY" \
        --base "$BASE_BRANCH" \
        --head "$BRANCH_NAME" 2>&1)
    
    PR_EXIT_CODE=$?
    
    if [ $PR_EXIT_CODE -eq 0 ]; then
        echo "✅ Pull request created successfully!"
        echo "🔗 $PR_OUTPUT"
        echo ""
        echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
        echo "✨ Success! Your changes are ready for review."
        echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
        echo ""
        echo "📌 Branch: $BRANCH_NAME"
        echo "🔗 PR: $PR_OUTPUT"
        echo "📦 Repository: https://github.com/$GITHUB_REPO"
    else
        echo "⚠️  PR creation failed!"
        echo "Error: $PR_OUTPUT"
        echo ""
        echo "But your branch was pushed successfully:"
        echo "📌 Branch: $BRANCH_NAME"
        echo "🔗 View branch: https://github.com/$GITHUB_REPO/tree/$BRANCH_NAME"
        echo ""
        echo "You can manually create a PR at:"
        echo "https://github.com/$GITHUB_REPO/compare/$BASE_BRANCH...$BRANCH_NAME"
    fi
fi

# Save logs if requested
if [ "${SAVE_LOGS:-false}" = "true" ]; then
    LOG_DIR="/logs"
    mkdir -p "$LOG_DIR"
    cp /tmp/claude-output.json "$LOG_DIR/claude-output-${TIMESTAMP}.json" 2>/dev/null || true
    echo ""
    echo "📄 Logs saved to: $LOG_DIR/claude-output-${TIMESTAMP}.json"
fi

echo ""
echo "🎉 Claude Code automation completed!"
